function pageTopic(
  slug: string,
  audience: DemoAudience,
  path: string,
  steps?: DemoStep[],
): DemoTopic {
  return {
    slug,
    audience,
    groupKey: groupKeyForSlug(audience, slug) || (audience === 'parents' ? 'parentGettingStarted' : 'staffGettingStarted'),
    src: withDemoQuery(path, audience),
    addressBar: demoAddressBar(path),
    steps: steps || pageWalk(),
  }
}


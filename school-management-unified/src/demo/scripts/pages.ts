export function pageWalk(extra: DemoStep[] = []): DemoStep[] {
  return [
    { action: 'wait', ms: 500 },
    { action: 'waitFor', target: '[data-demo="page"], main, h1', ms: 8000 },
    demoSay('demo.say.page'),
    { action: 'move', target: '.fk-page-header h1, [data-demo="page"] h1, h1' },
    { action: 'wait', ms: 350 },
    demoSay('demo.say.filter'),
    { action: 'scroll', target: '[data-demo="filter"], select.fk-field, #group-select' },
    { action: 'move', target: '[data-demo="filter"], select.fk-field, #group-select' },
    { action: 'wait', ms: 280 },
    demoSay('demo.say.primary'),
    { action: 'scroll', target: '[data-demo="primary"], a.fk-btn--primary, .fk-btn--primary' },
    { action: 'move', target: '[data-demo="primary"], a.fk-btn--primary, .fk-btn--primary' },
    { action: 'wait', ms: 280 },
    demoSay('demo.say.row'),
    { action: 'scroll', target: '[data-demo="row"], tbody tr' },
    { action: 'move', target: '[data-demo="row"], tbody tr' },
    { action: 'wait', ms: 800 },
    ...extra,
  ]
}

function typeField(target: string, text: string): DemoStep[] {
  return [
    { action: 'scroll', target },
    { action: 'move', target },
    { action: 'type', target, text },
    { action: 'wait', ms: 160 },
  ]
}

function clickTarget(target: string): DemoStep[] {
  return [
    { action: 'scroll', target },
    { action: 'move', target },
    { action: 'wait', ms: 200 },
    { action: 'click', target },
    { action: 'wait', ms: 450 },
  ]
}

function clickNext(): DemoStep[] {
  return [
    { action: 'waitFor', target: '[data-demo="next"]:not([disabled])', ms: 8000 },
    ...clickTarget('[data-demo="next"]:not([disabled])'),
  ]
}

function studentDetailsFlow(): DemoStep[] {
  return [
    { action: 'waitFor', target: '[data-demo="first-name-ar"]', ms: 10000 },
    ...typeField('[data-demo="first-name-ar"]', DEMO_CHILD_FIRST_AR),
    ...typeField('[data-demo="first-name-en"]', DEMO_CHILD_FIRST_EN),
    ...typeField('[data-demo="last-name-ar"]', DEMO_CHILD_LAST_AR),
    ...typeField('[data-demo="last-name-en"]', DEMO_CHILD_LAST_EN),
    ...typeField('[data-demo="id-number"]', DEMO_CIVIL_ID),
    ...clickTarget('[data-demo="gender-male"]'),
    ...typeField('[data-demo="nationality"]', DEMO_NATIONALITY),
    ...typeField('[data-demo="dob"]', DEMO_DOB),
    ...clickNext(),
  ]
}

